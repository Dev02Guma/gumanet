-- 1. Presentaciones hermanas: los artículos con el mismo GRUPO suman inventario y demanda en unidades mínimas
CREATE TABLE dbo.tbl_reorder_grupo_articulo (
    ARTICULO     VARCHAR(20)  NOT NULL CONSTRAINT PK_tbl_reorder_grupo_articulo PRIMARY KEY,
    GRUPO        VARCHAR(20)  NOT NULL,
    ACTIVO       BIT          NOT NULL CONSTRAINT DF_tbl_reorder_grupo_articulo_ACTIVO DEFAULT 1,
    FECHA_CREA   DATETIME     NOT NULL CONSTRAINT DF_tbl_reorder_grupo_articulo_FECHA DEFAULT GETDATE()
);
CREATE INDEX IX_tbl_reorder_grupo_articulo_GRUPO ON dbo.tbl_reorder_grupo_articulo (GRUPO);
GO

